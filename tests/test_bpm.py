def _sum_db(*levels):
    return 10 * np.log10(sum(10 ** (np.asarray(x) / 10) for x in levels))


def test_table_d2():
    args = dict(alpha=1.516, c=0.3048, U=71.3, f=F, L=0.4572, r=1.22, theta=90.0, phi=90.0, trip=bpm.TRIP_NONE,
                nu=VISC, c0=C0)
    p, s, a, _ = bpm.tblte(**args)
    lam = bpm.lblvs(**args)
    got = np.column_stack([p, s, a, lam, _sum_db(p, s, a, lam)])
    assert np.max(np.abs(got - D2)) < 0.02


def test_table_d3():
    nseg = 10
    args = dict(alpha=np.full(nseg, 5.4), c=0.1524, U=71.3, f=F, L=0.0305, r=1.22, theta=90.0, phi=90.0,
                trip=bpm.TRIP_HEAVY, nu=VISC, c0=C0)
    p, s, a, _ = bpm.tblte(**args)
    p, s, a = (_sum_db(*x) for x in (p, s, a))
    tip = bpm.tip(alpha_tip=7.7, c=0.1524, U=71.3, f=F, r=1.22, theta=90.0, phi=90.0, c0=C0, round_tip=True)
    got = np.column_stack([p, s, a, tip, _sum_db(p, s, a, tip)])
    # the report prints the separation level only down to -90 dB
    got[:, 2] = np.maximum(got[:, 2], -90.0)
    err = np.abs(got - D3)
    assert np.max(err[:, [0, 1, 2, 4]]) < 0.02
    # the printed tip column fits the listing's equations with a Strouhal number 0.33 % lower (an input or constant
    # of the run that made the table, not in the listing): up to 0.19 dB where the tip is 70 dB below the total
    assert np.max(err[:, 3]) < 0.2
